// Copies the generated product photos (admin/public/products/*.jpg) into the
// mobile app as bundled assets for the offline demo APK, and writes
// mobile/src/demo/images.js (product id → require()).
//   node scripts/bundle-demo-images.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { catalog } from './catalog.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, '..', 'public', 'products');
const mobile = path.join(here, '..', '..', 'mobile');
const dest = path.join(mobile, 'assets', 'products');
fs.mkdirSync(dest, { recursive: true });

const lines = [];
const missing = [];
for (const p of catalog) {
  const from = path.join(src, `${p.id}.jpg`);
  if (!fs.existsSync(from)) {
    missing.push(p.id);
    continue;
  }
  await sharp(from).resize(600, 600, { fit: 'contain', background: '#ffffff' }).jpeg({ quality: 80, mozjpeg: true })
    .toFile(path.join(dest, `${p.id}.jpg`));
  lines.push(`  '${p.id}': require('../../assets/products/${p.id}.jpg'),`);
}

fs.writeFileSync(
  path.join(mobile, 'src', 'demo', 'images.js'),
  `// Generated by admin/scripts/bundle-demo-images.mjs – maps product id → bundled image.\n/* eslint-disable global-require */\nexport default {\n${lines.join('\n')}\n};\n`,
);
console.log(`Bundled ${lines.length} images.${missing.length ? ` Missing: ${missing.join(', ')}` : ''}`);
